//! Keep timing quirks (including unreachable frame 15/20 in period 15),
//! collision sizes, ANM variants and sound suppression exactly as the source.

pub(super) struct ShotDef {
    pub wait: i32,
    pub frame: i32,
    pub motion: [f32; 2],
    pub size: [f32; 2],
    pub angle: f32,
    pub speed: f32,
    pub damage: i32,
    pub spawn: u8,
    pub bt: u8,
    pub script: i32,
    pub sound: bool,
}

macro_rules! shot {
    ($wait:expr, $frame:expr, $mx:expr, $my:expr, $sx:expr, $sy:expr, $degrees:expr, $speed:expr, $damage:expr, $spawn:expr, $bt:expr, $script:expr, $sound:expr) => {
        ShotDef {
            wait: $wait,
            frame: $frame,
            motion: [$mx, $my],
            size: [$sx, $sy],
            // Original RADIANS receives an unsuffixed double literal and a float PI.
            angle: ($degrees * std::f32::consts::PI as f64 / 180.0) as f32,
            speed: $speed,
            damage: $damage,
            spawn: $spawn,
            bt: $bt,
            script: $script,
            sound: $sound,
        }
    };
}

